# =================================================================
# 원인을 특정하지 못한 먹통(로그에 예외 하나 없이 조용히 멈춤 — 파이썬
# 레벨이 아니라 Wi-Fi 드라이버/네트워크 스택 내부에서 멈추는 것으로 추정)
# 에서 자동으로 복구하기 위한 최후의 안전망입니다.
#
# ⚠️ RP2040/RP2350의 WDT는 한번 켜면 재부팅 전까지 절대 끌 수 없습니다.
# 그래서 예전에는 일부러 안 썼습니다 — Thonny에서 스크립트를 정지(Ctrl+C)
# 하면 feed가 끊겨 8초 뒤 강제 재부팅이 반복돼 개발이 불가능했기 때문입니다.
# 지금은 Thonny를 쓰지 않고 웹 에디터/OTA로만 개발하므로 그 제약이 사라져
# 다시 도입했습니다. 만약 다시 Thonny로 개발할 일이 생기면, WDT_ENABLED를
# False로 두고 저장하면(웹 에디터로) 다음 부팅부터 워치독이 꺼집니다.
#
# 주의: WDT를 켠 뒤에는 8초 이상 걸릴 수 있는 모든 구간에서 feed()를
# 불러줘야 합니다 (Wi-Fi 재접속, 웹 에디터 파일 저장, OTA 다운로드 등).
# =================================================================
import machine

WDT_ENABLED = True
WDT_TIMEOUT_MS = 8000  # RP2040/RP2350 하드웨어 최대치(약 8.3초) 안쪽 값

_wdt = None


def start():
    """워치독을 시작합니다. 부팅~Wi-Fi 연결(최대 24초+)이 끝난 뒤에
    호출해야 합니다 — 그 전에 켜면 부팅 도중 리셋 루프에 빠집니다.
    이미 시작했으면 아무것도 하지 않습니다(중복 생성 방지)."""
    global _wdt
    if _wdt is not None or not WDT_ENABLED:
        return
    try:
        _wdt = machine.WDT(timeout=WDT_TIMEOUT_MS)
        print(f"🐕 하드웨어 워치독 시작 ({WDT_TIMEOUT_MS}ms) — 먹통 시 자동 재부팅됩니다")
    except Exception as e:
        print(f"⚠️ 워치독 시작 실패 (계속 진행): {type(e).__name__}: {e}")


def feed():
    """워치독 타이머를 리셋합니다. 시작 전이면 아무것도 하지 않으므로
    부팅 경로에서도 마음 놓고 부를 수 있습니다."""
    if _wdt is not None:
        _wdt.feed()


def is_active():
    return _wdt is not None
